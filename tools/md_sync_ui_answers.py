"""PG-ANSWER-UI (part d): the one-way mirror of UI answers for the router.

``ui_answers_md`` renders the keeper's ``answers`` rows that an operator answered
from the UI (``answer_source == "ui"``, still no ``decision_id``) as one
``UI-ANSWER`` bullet per answer, so the router can read what the operator decided
and record the D-row itself.  The keeper already owns the answer
(``operator_answer`` writes the ``answered`` event); this file only PRODUCES the
line, and an answer that carries a ``decision_id`` has been recorded already, so
it is skipped.

The view is generated (PL-38): nothing parses it back, and redaction is always
the LAST transform -- the same structural-keyword neutralisation
(``md_sync_archive._neutralise_keywords``) and the same
``md_sync_parse.redact`` + ``credential_guard.mask`` pair the archive tool runs.

    md_sync.py --ui-answers --answers-out PATH --url U --token-file F
               [--project routing] [--dry-run | --apply] [--status-file FILE]
"""
import argparse
import json
import os
import tempfile

import apply_batch
import md_sync_plan  # noqa: F401  (puts src/ on sys.path, as md_sync_archive does)
import md_sync_archive as arch

USAGE = ("usage: md_sync.py --ui-answers --answers-out PATH --url U --token-file F "
         "[--project NAME] [--dry-run | --apply] [--status-file FILE]\n")

HEADER = "# UI answers (generated by md_sync.py --ui-answers, do not edit)\n"
TEXT_CAP = 300


def _ui_text(value):
    """One safe single line: collapse, ``|`` -> ``/``, truncate, neutralise, redact LAST.

    The pipe join runs before the cut so a credential split by a pipe is joined
    while still detectable, and ``_finalise_cell`` ends with redaction, never
    starts with it.
    """
    collapsed = " ".join(str(value if value is not None else "").split())
    shaped = collapsed.replace("|", "/")[:TEXT_CAP]
    return arch._finalise_cell(arch._neutralise_keywords(shaped), "description")


def ui_answers_md(items, project=None):
    """The view text for the keeper's ``answers`` rows; *items* in any order."""
    rows = []
    for row in items or []:
        if not isinstance(row, dict) or row.get("answer_source") != "ui":
            continue
        if row.get("decision_id"):
            continue                      # the router has recorded it already
        if project is not None and row.get("project") != project:
            continue
        rows.append(row)
    rows.sort(key=lambda row: str(row.get("key") or ""))
    out = [HEADER]
    for row in rows:
        key = _ui_text(row.get("key"))
        answer = _ui_text(row.get("answer"))
        choice = _ui_text(row.get("answer_choice_id")) or answer
        user = _ui_text(row.get("answer_user"))
        ts = _ui_text(row.get("done_at"))
        out.append(f'- UI-ANSWER {key} = "{answer}" '
                   f"(choice {choice}, by {user}, {ts}) "
                   "-> router: record the D-row, then ANSWERS.md\n")
    return "".join(out)


def _write_atomic(path, text):
    """tmp + ``os.replace``, always mode 0600; any failure keeps the old file."""
    folder = os.path.dirname(os.path.abspath(path)) or "."
    fd, tmp = tempfile.mkstemp(prefix=".uianswers.", dir=folder)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", errors="replace") as handle:
            handle.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _answers_rows(session):
    """The keeper's ``answers`` read verb through the archive mode's ``Session``.

    ``Session.get`` only accepts a JSON object (``snapshot``, ``whoami``); this
    verb replies with a list, so the same authenticated call is parsed here.
    """
    rows = json.loads(session._call("answers").decode("utf-8"))
    if not isinstance(rows, list):
        raise apply_batch.ApiError("bad_reply", "answers is not a list")
    return rows


def ui_answers_main(argv, out, err, write_status):
    """``md_sync.py --ui-answers ...``; *write_status* is md_sync's atomic status writer."""
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--ui-answers", action="store_true")
    for name in ("answers-out", "token-file"):
        parser.add_argument("--" + name, required=True)
    parser.add_argument("--url", default=apply_batch.DEFAULT_URL)
    parser.add_argument("--project", default="routing")
    parser.add_argument("--status-file")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--apply", action="store_true")
    status = {"ts": None, "mode": "ui-answers", "ui_answers": 0,
              "written": False, "error": None}
    try:
        opts = parser.parse_args(argv)
    except SystemExit:
        err.write(USAGE)
        write_status(arch._flag(argv, "--status-file"), status,
                     "error: bad arguments (see usage)", err)
        return 2

    def stop(rc, error):
        write_status(opts.status_file, status, error, err)
        return rc

    try:
        token = apply_batch.read_token(opts.token_file)
    except (OSError, apply_batch.BatchError) as exc:
        err.write(f"error: {exc}\n")
        return stop(2, f"error: {exc}")
    try:
        rows = _answers_rows(apply_batch.Session(opts.url, token))
    except (apply_batch.ApiError, ValueError) as exc:
        msg = (f"error: cannot read the live graph: {exc.code} {exc.msg}"
               if isinstance(exc, apply_batch.ApiError)
               else f"error: cannot read the live graph: {exc.__class__.__name__}")
        err.write(msg + "\n")
        return stop(2, msg)
    try:
        text = ui_answers_md(rows, project=opts.project)
    except Exception as exc:
        err.write(f"error: malformed answers data: {exc.__class__.__name__}\n")
        return stop(2, f"error: malformed answers data: {exc.__class__.__name__}")
    count = len(text.splitlines()) - 1
    status["ui_answers"] = count
    if not opts.apply:
        out.write(f"dry run: would write {count} UI answers to {opts.answers_out} "
                  "(no file written)\n")
        return stop(0, None)
    try:
        _write_atomic(opts.answers_out, text)
    except Exception as exc:
        err.write(f"error: cannot write {opts.answers_out}: {exc.__class__.__name__}\n")
        return stop(2, f"error: cannot write {opts.answers_out}: {exc.__class__.__name__}")
    status["written"] = True
    out.write(f"md-sync ui-answers: wrote {count} UI answers to {opts.answers_out}\n")
    return stop(0, None)
