def ui_run(srv, token, out_path, *extra):
    out, err = io.StringIO(), io.StringIO()
    rc = md_sync.main(["--ui-answers", "--answers-out", str(out_path),
                       "--url", srv.base_url, "--token-file", token, *extra],
                      out=out, err=err)
    return rc, out.getvalue(), err.getvalue()


