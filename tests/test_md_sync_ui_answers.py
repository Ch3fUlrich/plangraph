# Credential-shaped fixtures are built at runtime (never as literals), as in
# tests/test_md_sync_archive.py: _SECRET is "abcd"+"1234".
_USER = "user"
_SECRET = "abcd" + "1234"
_PAIR = _USER + "/" + _SECRET
_HEX16 = "0123456789abcdef"

CHOICES = {"options": [{"id": "ship", "label": "Ship it", "consequence": "go now"},
                       {"id": "hold", "label": "Hold off"}],
           "default": "hold", "deadline": None, "blocks": None}


def _row(key, text, source="ui", user="ops", choice_id=None,
         did=None, at="2026-10-05T00:00:00+00:00", project="routing"):
    """One ``views.answers`` row as the keeper sends it (UI answers carry the extras)."""
    row = {"key": key, "project": project, "title": key, "kind": "question",
           "answer": text, "decision_id": did, "done_at": at}
    if source is not None:
        row["answer_source"] = source
    if user is not None and source == "ui":
        row["answer_user"] = user
        if choice_id is not None:
            row["answer_choice_id"] = choice_id
    return row


def _bullets(text):
    lines = text.splitlines()
    assert lines[0] == ("# UI answers (generated by md_sync.py --ui-answers, "
                        "do not edit)")
    return lines[1:]


# ------------------------------------------------------------------ generator
def test_exact_bullet_format_and_header():
    text = uia.ui_answers_md([_row("routing:Q-1", "Ship it", choice_id="ship")])
    assert _bullets(text) == [
        '- UI-ANSWER routing:Q-1 = "Ship it" (choice ship, by ops, '
        '2026-10-05T00:00:00+00:00) -> router: record the D-row, then ANSWERS.md']
    assert text.endswith("\n") and "\r" not in text


def test_free_text_answer_repeats_the_text_as_the_choice():
    text = uia.ui_answers_md([_row("routing:Q-2", "go backoff")])
    assert "(choice go backoff, by ops," in _bullets(text)[0]


def test_only_ui_undecided_answers_appear():
    rows = [_row("routing:Q-UI", "yes"),
            _row("routing:Q-ROUTER", "no", source=None, user=None, did="D-1"),
            _row("routing:Q-DECIDED", "late", did="D-2"),
            _row("routing:Q-CLI", "x", source="cli", user=None)]
    assert [b.split()[2] for b in _bullets(uia.ui_answers_md(rows))] == ["routing:Q-UI"]


def test_empty_view_is_the_header_only():
    assert uia.ui_answers_md([]) == ("# UI answers (generated by md_sync.py "
                                     "--ui-answers, do not edit)\n")


def test_project_filter():
    rows = [_row("routing:Q-A", "a"), _row("server:Q-B", "b", project="server")]
    assert [b.split()[2] for b in _bullets(uia.ui_answers_md(rows))] == [
        "routing:Q-A", "server:Q-B"]                    # project=None: every project
    assert [b.split()[2] for b in _bullets(
        uia.ui_answers_md(rows, project="routing"))] == ["routing:Q-A"]
    assert [b.split()[2] for b in _bullets(
        uia.ui_answers_md(rows, project="server"))] == ["server:Q-B"]
    assert _bullets(uia.ui_answers_md(rows, project="none")) == []


def test_order_is_by_key_and_deterministic():
    rows = [_row("routing:Q-3", "c"), _row("routing:Q-1", "a"), _row("routing:Q-2", "b")]
    first = uia.ui_answers_md(rows)
    assert first == uia.ui_answers_md(list(reversed(rows)))
    assert [b.split()[2] for b in _bullets(first)] == [
        "routing:Q-1", "routing:Q-2", "routing:Q-3"]


def test_hostile_text_is_neutralised_and_redacted_last():
    poison = (f"Options: see {{x}} | line1\nline2 credential {_PAIR} "
              f"token {_HEX16 * 3}")
    text = uia.ui_answers_md([_row("routing:Q-P", poison)])
    (bullet,) = _bullets(text)
    assert len(text.splitlines()) == 2                     # single-lined
    assert arch._NEUTRAL_COLON in bullet                   # Options: neutralised
    assert re.search(r"(?i)options:", bullet) is None
    assert "{" not in bullet and "}" not in bullet         # braces -> parens
    assert _PAIR not in bullet and "abcd1234" not in bullet
    assert _HEX16 * 3 not in bullet and _HEX16 * 2 not in bullet
    assert "[redacted]" in bullet
    assert cg.find_shapes(bullet) == []


def test_pipe_split_credential_is_joined_before_redaction():
    text = uia.ui_answers_md(
        [_row("routing:Q-S", f"credential {_USER}|{_SECRET} ok")])
    (bullet,) = _bullets(text)
    assert _SECRET not in bullet and _PAIR not in bullet
    assert "[redacted]" in bullet and cg.find_shapes(bullet) == []


def test_leading_bullet_marker_neutralised():
    text = uia.ui_answers_md([_row("routing:Q-B", "* urgent pick")])
    (bullet,) = _bullets(text)
    assert '= "urgent pick"' in bullet


def test_text_is_truncated_at_300():
    long_text = " ".join(["alpha"] * 80)                  # 479 chars, no redactable run
    text = uia.ui_answers_md([_row("routing:Q-L", long_text)])
    (bullet,) = _bullets(text)
    quoted = re.match(r'- UI-ANSWER \S+ = "(.*)" \(choice', bullet).group(1)
    assert quoted == long_text[:300] and len(quoted) == 300


def test_views_answers_passes_source_user_through():
    items = [
        {"key": "p:Q", "project": "p", "title": "t", "kind": "question",
         "state": "done", "done_at": "t1",
         "answer": {"text": "Ship it", "decision_id": None, "source": "ui",
                    "user": "ops", "choice_id": "ship"}},
        {"key": "p:R", "project": "p", "title": "t", "kind": "question",
         "state": "done", "done_at": "t2",
         "answer": {"text": "no", "decision_id": "D-1", "source": None,
                    "user": None}}]
    rows = {r["key"]: r for r in views.answers(items)}
    assert rows["p:Q"]["answer_source"] == "ui"
    assert rows["p:Q"]["answer_user"] == "ops"
    assert rows["p:Q"]["answer_choice_id"] == "ship"
    assert "answer_source" not in rows["p:R"] and "answer_user" not in rows["p:R"]


