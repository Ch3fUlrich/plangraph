"""PG-ANSWER-UI (part d): md-sync's one-way mirror of UI answers for the router.

``ui_answers_md`` renders the keeper ``answers`` rows answered from the UI
(``answer.source == "ui"``, no ``decision_id`` yet) as ``UI-ANSWER`` bullets;
``md_sync --ui-answers`` (default OFF) writes that generated view atomically
(mode 0600) only on ``--apply``.  The file is NEVER parsed back (PL-38) and
redaction is the LAST transform, reusing ``md_sync_archive``'s helpers.

Mutation killed: router answers or decided answers emitted; the fixed header or
bullet format drifting; keywords, pipes, newlines and secrets reaching the file
intact; text longer than 300 chars; nondeterministic order; --dry-run writing;
a non-0600 or leftover-temp write; the status file carrying answer text.
"""
