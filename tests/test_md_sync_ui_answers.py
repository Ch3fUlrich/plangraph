def test_apply_writes_only_the_undecided_ui_answers(srv, token, tmp_path):
    target = tmp_path / "UI-ANSWERS.md"
    rc, out, err = ui_run(srv, token, target, "--apply")
    assert rc == 0, err
    keys = [b.split()[2] for b in _bullets(target.read_text(encoding="utf-8"))]
    assert keys == ["routing:Q-CHOICE", "routing:Q-FREE"]   # Q-ROUTER (source None),
    # Q-SERVER (project), the D-close and non-UI items never appear
    assert '"Ship it"' in target.read_text(encoding="utf-8")
    assert "(choice ship, by ops-admin," in target.read_text(encoding="utf-8")
    assert "wrote 2 UI answers" in out


def test_dry_run_is_the_default_and_writes_nothing(srv, token, tmp_path):
    target = tmp_path / "UI-ANSWERS.md"
    rc, out, err = ui_run(srv, token, target)
    assert rc == 0 and not target.exists() and "dry run" in out
    assert "2 UI answers" in out
    target.write_text("old", encoding="utf-8")
    ui_run(srv, token, target, "--dry-run")
    assert target.read_text(encoding="utf-8") == "old"


def test_apply_writes_atomically_with_mode_0600(srv, token, tmp_path):
    target = tmp_path / "UI-ANSWERS.md"
    target.write_text("old", encoding="utf-8")
    os.chmod(target, 0o644)                                 # rewritten content is 0600
    rc, _out, err = ui_run(srv, token, target, "--apply")
    assert rc == 0, err
    assert stat.S_IMODE(os.stat(target).st_mode) == 0o600
    assert [p.name for p in tmp_path.iterdir()
            if p.name.startswith(".uianswers.")] == []


