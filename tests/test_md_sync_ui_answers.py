def test_archive_and_default_dispatches_are_unchanged(srv, token, tmp_path):
    # --ui-answers, the import (no flag) and --archive-answers each keep their own path.
    rc, _out, err = ui_run(srv, token, tmp_path / "M.md", "--apply")
    assert rc == 0, err
    out2, err2 = io.StringIO(), io.StringIO()
    assert md_sync.main(["--url", srv.base_url, "--token-file", token],
                        out=out2, err=err2) == 2
    assert md_sync.USAGE in err2.getvalue()
    out3, err3 = io.StringIO(), io.StringIO()
    rc = md_sync.main(["--archive-answers", "--questions-out", str(tmp_path / "Q.md"),
                       "--url", srv.base_url, "--token-file", token],
                      out=out3, err=err3)
    assert rc == 0 and "dry run" in out3.getvalue()
